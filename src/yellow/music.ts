/** Crystal track for a Yellow song name or the song id stored in the map song table. */
export function crystalMusic(song: string | number): number | undefined {
  if (typeof song === "string") return CRYSTAL[song];
  const name = Object.keys(MUSIC).find(k => MUSIC[k].id === song);
  return name ? CRYSTAL[name] : undefined;
}
