#!/usr/bin/env node
// Builds src/yellow/generated/crystal.ts from a local pret/pokecrystal checkout
// built as the supported cartridge (SHA-1 f4cd194bdee0d04ca4eac29e09b8e4e9d818c133).
//
// The Yellow adventure can draw Kanto with the Crystal cartridge's own tiles,
// palettes and overworld sprites. The output only holds ROM offsets and
// identifier names; the graphics are read from the player's cartridge at
// runtime. Usage: node scripts/crystal-symbols.mjs ../pokecrystal
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const root = process.argv[2] ?? "../pokecrystal";
const read = path => readFileSync(join(root, path), "utf8");

const sym = new Map();
for (const line of read("pokecrystal.sym").split("\n")) {
  const m = /^([0-9a-f]{2}):([0-9a-f]{4}) (\S+)$/.exec(line.trim());
  if (!m) continue;
  const bank = parseInt(m[1], 16), addr = parseInt(m[2], 16);
  if (addr >= 0x8000 || (bank === 0 && addr >= 0x4000)) continue;
  sym.set(m[3], bank === 0 ? addr : bank * 0x4000 + (addr - 0x4000));
}
const WANTED = [
  "Tilesets", "TilesetBGPalette", "EnvironmentColorsPointers.OutdoorColors", "EnvironmentColorsPointers.IndoorColors",
  "EnvironmentColorsPointers.DungeonColors", "RoofPals", "HousePalette", "MansionPalette1", "MansionPalette2",
  "MapObjectPals", "OverworldSprites", "AnimateWaterTile.WaterTileFrames", "AnimateFlowerTile.FlowerTileFrames",
];
const symbols = {};
for (const name of WANTED) {
  const v = sym.get(name);
  if (v === undefined) throw Error(`Missing symbol ${name}`);
  symbols[name] = v;
}

/** `const_def` lists: each `const NAME` takes the next value. */
function constants(path, prefix) {
  const out = {};
  let value = 0;
  for (const line of read(path).split("\n")) {
    const def = /^\s*const_def\s*(\$?[0-9a-fA-F]+)?/.exec(line);
    if (def) {
      value = def[1] ? (def[1].startsWith("$") ? parseInt(def[1].slice(1), 16) : +def[1]) : 0;
      continue;
    }
    const next = /^\s*const_next\s+\$?([0-9a-fA-F]+)/.exec(line);
    if (next) {
      value = parseInt(next[1], line.includes("$") ? 16 : 10);
      continue;
    }
    const c = /^\s*const\s+(\w+)/.exec(line);
    if (c) {
      if (c[1].startsWith(prefix)) out[c[1].slice(prefix.length)] = value;
      value++;
    }
  }
  return out;
}
const tilesets = constants("constants/tileset_constants.asm", "TILESET_");
const sprites = constants("constants/sprite_constants.asm", "SPRITE_");
const palettes = constants("constants/sprite_data_constants.asm", "PAL_OW_");

// Map groups: `newgroup` starts each group; `map_const` lists its maps.
const groups = {};
let group = 0;
for (const line of read("constants/map_constants.asm").split("\n")) {
  if (/^\s*newgroup\b/.test(line)) group++;
  const m = /^\s*map_const\s+(\w+),/.exec(line);
  if (m) groups[m[1]] = group;
}

const hex = n => "0x" + n.toString(16);
const record = (name, doc, entries, format = v => String(v)) =>
  `/** ${doc} */\nexport const ${name}: Record<string, number> = {\n${Object.entries(entries).map(([k, v]) => `  ${/^[A-Za-z_]\w*$/.test(k) ? k : JSON.stringify(k)}: ${format(v)},`).join("\n")}\n};\n`;
const out = `// Generated by scripts/crystal-symbols.mjs from pret/pokecrystal. Offsets and names only.
${record("CRYSTAL_SYM", "Cartridge offsets of the Crystal tables the Yellow renderer reads.", symbols, hex)}
${record("CRYSTAL_TILESET", "Crystal tileset ids.", tilesets)}
${record("CRYSTAL_SPRITE", "Crystal overworld sprite ids.", sprites)}
${record("CRYSTAL_OW_PALETTE", "Crystal overworld sprite palettes.", palettes)}
${record("CRYSTAL_MAP_GROUP", "Crystal map group of each map, which sets its roof colors.", groups)}`;
mkdirSync("src/yellow/generated", { recursive: true });
writeFileSync("src/yellow/generated/crystal.ts", out);
console.log(`Wrote ${Object.keys(symbols).length} offsets, ${Object.keys(tilesets).length} tilesets, ${Object.keys(sprites).length} sprites, ${Object.keys(groups).length} maps.`);
